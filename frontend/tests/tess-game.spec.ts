import { expect, test, type Page } from '@playwright/test'

async function enterGame(page: Page) {
  await page.getByRole('button', { name: 'Jugar Cazadores de mundos ocultos' }).click()
  await expect(page.getByRole('heading', { name: 'Cazadores de mundos ocultos' })).toBeVisible()
}

test('explora, mide píxeles, estima un período y guarda un informe con evidencia', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Ir a Observaciones TESS', exact: true }).click()
  await enterGame(page)
  await expect(page.getByRole('button', { name: /Vela 04/ })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Capturar imagen' })).toBeDisabled()
  const sky = page.getByLabel(/Visor 3D del cielo/)
  await expect(sky).toBeVisible()
  await page.getByRole('button', { name: 'Cámara 3', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Cámara 3', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Acercar', exact: true }).click()
  await expect(page.getByText('Cámara 3 · 1,5×')).toBeVisible()
  await page.getByRole('button', { name: 'Centrar Vela 01' }).click()
  await expect(page.getByText('Objetivo centrado')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('tess-observacion.png') })

  const capture = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/game/sensor/vela/0') && response.ok())
  await page.getByRole('button', { name: 'Capturar imagen' }).click()
  expect((await (await capture).json()).counts[0]).toHaveLength(49)
  await expect(page.getByRole('group', { name: 'Píxeles del detector simulado' }).getByRole('button')).toHaveCount(49)
  const acceleration = page.getByRole('button', { name: 'Acelerar 12 días' })
  await acceleration.click()
  await expect(page.getByText('12 de 24 días')).toBeVisible()
  await acceleration.click()
  await expect(page.getByText('24 de 24 días')).toBeVisible()
  await page.getByLabel('Imagen del detector').press('End')
  await expect(page.getByText('Día 24,00')).toBeVisible()
  await expect(page.getByText(/cadencias durante la descarga simulada/)).toBeVisible()
  await page.getByLabel('Apertura fotométrica').selectOption('wide')
  await expect(page.getByText('Día 24,00')).toBeVisible()
  await page.getByRole('button', { name: 'Analizar curva de luz' }).click()
  await expect(page.getByRole('button', { name: 'Ejecutar TLS' })).toBeDisabled()
  await page.getByLabel('Filtrar calidad').uncheck()
  await expect(page.getByRole('button', { name: 'Procesada', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const bls = page.waitForResponse(response => response.url().endsWith('/game/analyze') &&
    response.request().postDataJSON().method === 'bls' && response.ok())
  await page.getByRole('button', { name: 'Ejecutar BLS' }).click()
  const analysis = await bls
  expect(analysis.request().postDataJSON().aperture).toBe('wide')
  expect((await analysis.json()).fit.period).toBeCloseTo(3.6, 1)
  await page.getByRole('button', { name: 'Superponer vueltas' }).click()
  await expect(page.getByRole('img', { name: 'Curva plegada de la misión' })).toBeVisible()
  await page.getByRole('button', { name: 'Preparar informe' }).click()
  await page.getByRole('radio', { name: 'Señal candidata a planeta' }).check()
  await page.getByRole('checkbox', { name: /Caídas que se repiten/ }).check()
  await page.getByRole('button', { name: 'Evaluar y guardar informe' }).click()
  await expect(page.getByRole('heading', { name: 'Conclusión correcta' })).toBeVisible()
  await expect(page.getByText('4 / 5 puntos')).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Descargar informe', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('informe-tess-vela.txt')
  await page.getByRole('button', { name: 'Siguiente misión' }).click()
  await expect(page.getByRole('button', { name: 'Centrar Vela 04' })).toBeVisible()
  await page.getByRole('button', { name: 'Volver al laboratorio' }).click()
  await expect(page.getByRole('heading', { name: 'Conectamos con NASA TESS' })).toBeFocused()
  await page.reload()
  await enterGame(page)
  await expect(page.getByRole('button', { name: 'Centrar Vela 04' })).toBeVisible()
  await page.getByRole('button', { name: 'Registro', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Descargar informe de Vela 01' })).toBeVisible()
  expect(errors).toEqual([])
})

test('activa conferencia en pantalla completa y compara BLS y TLS reales en móvil', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/')
  await enterGame(page)
  await page.getByRole('button', { name: 'Conferencia', exact: true }).click()
  await expect(page.getByText(/12 min/)).toBeVisible()
  await page.getByRole('button', { name: 'Modo Presentación' }).click()
  await expect(page.locator('.lab')).toHaveClass(/in-presentation/)
  await page.getByRole('button', { name: 'Salir de presentación' }).click()
  await page.getByRole('button', { name: 'Científico', exact: true }).click()
  await expect(page.getByText('NASA TESS · datos archivados')).toBeVisible()
  await page.getByRole('button', { name: 'Abrir observaciones reales' }).click()
  await expect(page.getByRole('img', { name: 'Curva de luz de la misión' })).toBeVisible()

  for (const method of ['bls', 'tls']) {
    const result = page.waitForResponse(response => response.url().endsWith('/game/analyze') &&
      response.request().postDataJSON().method === method && response.ok(), { timeout: 75_000 })
    await page.getByRole('button', { name: 'Ejecutar ' + method.toUpperCase() }).click()
    const data = await (await result).json()
    expect(Math.abs(data.fit.period - 6.2679)).toBeLessThan(0.1)
    expect(data.power.length).toBeGreaterThan(10)
  }
  await expect(page.getByText('TLS agrupa las cadencias en intervalos de 10 minutos.')).toBeVisible()
  await page.getByRole('button', { name: 'Superponer vueltas' }).click()
  await expect(page.getByRole('img', { name: 'Curva plegada de la misión' }).locator('.main-svg').first()).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
  await page.screenshot({ path: testInfo.outputPath('tess-cientifico.png'), fullPage: true })
  await page.getByRole('button', { name: 'Preparar informe' }).click()
  await page.getByRole('radio', { name: 'Señal de un planeta conocido' }).check()
  await page.getByRole('checkbox', { name: /Caídas que se repiten/ }).check()
  await page.getByRole('button', { name: 'Evaluar y guardar informe' }).click()
  await expect(page.getByText('5 / 5 puntos')).toBeVisible()
  await page.getByRole('button', { name: 'Ver registro' }).click()
  await expect(page.getByText(/No necesitas viajar hasta otro sistema estelar/)).toBeVisible()
})
